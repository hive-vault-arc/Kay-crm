import { mkdir } from "node:fs/promises";
import path from "node:path";
import { clearActorContext, test, expect, signIn, createActor, removeActor } from "../helpers/auth";
import { createLead } from "../helpers/leads";
import { testControl } from "../helpers/api-process";

test("SP05 visible Chrome: desktop/mobile, keyboard, touch, duplicate/private and columns", async ({ page, browser, baseURL }) => {
  test.setTimeout(150_000);
  const agent = await createActor("agent");
  const other = await createActor("agent");
  const artifact = path.resolve("output/playwright");
  await mkdir(artifact, { recursive: true });
  const errors: string[] = [];
  const monitor = (target: typeof page) => {
    target.on("pageerror", () => errors.push("APPLICATION_PAGE_ERROR"));
    target.on("console", message => {
      if (message.type() === "error" && !/^Failed to load resource: the server responded with a status of (401|403|404|409|422|503)\b/.test(message.text())) errors.push("APPLICATION_CONSOLE_ERROR");
    });
  };
  monitor(page);
  const touch = await browser.newContext({ baseURL, ignoreHTTPSErrors: true, viewport: { width: 360, height: 800 }, hasTouch: true, locale: "fr-FR", timezoneId: "Africa/Casablanca" });
  const mobile = await touch.newPage();
  monitor(mobile);
  try {
    await signIn(page, agent);
    const name = "SP05 organisation synthétique au nom français volontairement long pour vérifier les retours à la ligne";
    const id = await createLead(page, name);
    await page.setViewportSize({ width: 1440, height: 900 });
    await page.screenshot({ path: path.join(artifact, "sp05-detail-desktop.png"), fullPage: true });
    await testControl("fixture", { action: "bulk-enquiries", id: agent.id, count: 51 });
    await page.goto("/leads");
    await expect(page.getByText("52 demande(s) accessible(s).", { exact: true })).toBeVisible();
    await page.screenshot({ path: path.join(artifact, "sp05-list-desktop.png"), fullPage: true });
    await page.screenshot({ path: path.join(artifact, "sp05-list-desktop-viewport.png") });
    await page.getByRole("button", { name: "Suivant", exact: true }).click();
    await expect(page.getByRole("button", { name: "Page 2", exact: true })).toBeDisabled();
    await page.getByRole("button", { name: "Page 1", exact: true }).click();
    const columns = page.getByRole("button", { name: "Colonnes", exact: true });
    await columns.focus(); await page.keyboard.press("Enter");
    await expect(page.getByRole("dialog", { name: "Colonnes des Leads", exact: true })).toBeVisible();
    await page.getByRole("checkbox", { name: "Demande", exact: true }).check();
    await page.getByRole("button", { name: "Monter Demande", exact: true }).click();
    await page.screenshot({ path: path.join(artifact, "sp05-columns-desktop.png"), fullPage: true });
    await page.screenshot({ path: path.join(artifact, "sp05-columns-desktop-viewport.png") });
    await page.keyboard.press("Escape"); await expect(columns).toBeFocused();
    await page.getByLabel("Rechercher un nom, téléphone ou e-mail", { exact: true }).fill("SP05 organisation");
    await page.getByRole("button", { name: "Appliquer", exact: true }).click();
    await expect(page.getByText("1 demande(s) accessible(s).", { exact: true })).toBeVisible();

    await signIn(mobile, agent);
    await mobile.getByRole("button", { name: "Ouvrir la navigation", exact: true }).tap();
    await mobile.getByRole("dialog", { name: "Navigation KAY", exact: true }).getByRole("link", { name: "Prospects", exact: true }).tap();
    await expect(mobile.getByText("52 demande(s) accessible(s).", { exact: true })).toBeVisible();
    await mobile.getByLabel("Rechercher un nom, téléphone ou e-mail", { exact: true }).fill("SP05 organisation");
    await mobile.getByRole("button", { name: "Appliquer", exact: true }).tap();
    await expect(mobile.getByText("1 demande(s) accessible(s).", { exact: true })).toBeVisible();
    await mobile.screenshot({ path: path.join(artifact, "sp05-list-mobile.png"), fullPage: true });
    const scroller = mobile.getByRole("region", { name: "Tableau des Leads, défilement horizontal", exact: true });
    await scroller.focus();
    await mobile.keyboard.press("ArrowRight");
    await expect.poll(() => scroller.evaluate(element => element.scrollLeft)).toBeGreaterThan(0);
    await scroller.evaluate(element => { element.scrollLeft = 0; });
    await mobile.getByRole("link", { name, exact: true }).tap();
    await expect(mobile.locator("main h1[data-route]")).toBeVisible();
    await expect(mobile.getByText("SP05 demande synthétique de contrôle", { exact: true })).toBeVisible();
    await mobile.screenshot({ path: path.join(artifact, "sp05-detail-mobile.png"), fullPage: true });
    await mobile.goto(`/leads/${id}/edit`);
    await expect(mobile.getByLabel("Description", { exact: true })).toBeEnabled();
    await mobile.getByLabel("Description", { exact: true }).fill("SP05 modification tactile synthétique");
    await mobile.getByRole("button", { name: "Enregistrer le prospect", exact: true }).tap();
    await expect(mobile.getByText("Prospect enregistré.", { exact: true })).toBeVisible();
    await mobile.screenshot({ path: path.join(artifact, "sp05-edit-mobile.png"), fullPage: true });
    await mobile.goto("/leads/new");
    await expect(mobile.getByRole("button", { name: "Créer le Lead", exact: true })).toBeEnabled();
    await mobile.getByLabel("Contact de la demande", { exact: true }).selectOption("existing");
    const chooseContact = mobile.getByRole("button", { name: `Choisir ${name}`, exact: true });
    await expect(chooseContact).toBeVisible();
    expect(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await chooseContact.scrollIntoViewIfNeeded();
    expect((await chooseContact.boundingBox())?.width).toBeLessThanOrEqual(328);
    await mobile.screenshot({ path: path.join(artifact, "sp05-selector-mobile-viewport.png") });
    await chooseContact.tap();
    await expect(mobile.getByText(`Contact choisi : ${name}`, { exact: true })).toBeVisible();
    await mobile.getByLabel("Contact de la demande", { exact: true }).selectOption("new");
    await mobile.getByLabel("Nom du contact", { exact: true }).fill("SP05 validation synthétique");
    await mobile.getByRole("button", { name: "Créer le Lead", exact: true }).tap();
    const invalidPhone = mobile.getByLabel("Téléphone 1 *", { exact: true });
    await expect(invalidPhone).toHaveAttribute("aria-invalid", "true");
    expect(await invalidPhone.evaluate(element => {
      const descriptions = (element.getAttribute("aria-describedby") ?? "").split(/\s+/).map(id => document.getElementById(id));
      return descriptions.some(node => node?.textContent?.includes("Choisissez l’indicatif")) && descriptions.some(node => node?.getAttribute("data-slot") === "form-message" && Boolean(node.textContent));
    })).toBe(true);
    await mobile.getByLabel("Nom du contact", { exact: true }).fill("SP05 nouvelle saisie synthétique");
    await mobile.getByLabel("Indicatif Téléphone 1 *", { exact: true }).selectOption("MA");
    await mobile.getByLabel("Téléphone 1 *", { exact: true }).fill("0600000001");
    await mobile.getByLabel("Langues parlées *", { exact: true }).selectOption("french");
    await mobile.getByLabel("Budget *", { exact: true }).selectOption("500.000 DH - 1.000.000 DH");
    await mobile.getByRole("button", { name: "Ajouter un téléphone", exact: true }).tap();
    await mobile.getByLabel("Indicatif Téléphone 2", { exact: true }).selectOption("US");
    await mobile.getByLabel("Téléphone 2", { exact: true }).fill("2025550101");
    await mobile.getByRole("radio", { name: "Principal 2", exact: true }).focus();
    await mobile.keyboard.press("Space");
    await expect(mobile.getByRole("radio", { name: "Principal 2", exact: true })).toBeChecked();
    await mobile.getByRole("button", { name: "Retirer le téléphone 2", exact: true }).tap();
    await expect(mobile.getByText("Numéro principal", { exact: true })).toBeVisible();
    await mobile.getByRole("button", { name: "Ajouter un e-mail", exact: true }).tap();
    await mobile.getByRole("button", { name: "Retirer l’e-mail 1", exact: true }).tap();
    for (const width of [320, 360, 768, 1024, 1440]) {
      await mobile.setViewportSize({ width, height: 900 });
      expect(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
      for (const field of ["Nom du contact", "Téléphone 1 *"]) expect((await mobile.getByLabel(field, { exact: true }).boundingBox())?.height).toBeGreaterThanOrEqual(44);
      expect((await mobile.getByRole("button", { name: "Créer le Lead", exact: true }).boundingBox())?.height).toBeGreaterThanOrEqual(44);
    }
    await mobile.setViewportSize({ width: 360, height: 800 });
    await mobile.getByRole("button", { name: "Créer le Lead", exact: true }).tap();
    const dialog = mobile.getByRole("alertdialog");
    await expect(dialog).toBeVisible();
    const bounds = await dialog.boundingBox();
    expect(bounds !== null && bounds.x >= 16 && bounds.width <= 328).toBe(true);
    await expect(dialog.getByRole("button", { name: "Conserver ma saisie", exact: true })).toBeFocused();
    await mobile.screenshot({ path: path.join(artifact, "sp05-duplicate-mobile.png"), fullPage: true });
    await mobile.screenshot({ path: path.join(artifact, "sp05-duplicate-mobile-viewport.png") });
    await mobile.keyboard.press("Escape");
    await expect(mobile.getByRole("button", { name: "Créer le Lead", exact: true })).toBeFocused();
    await expect(mobile.getByLabel("Nom du contact", { exact: true })).toHaveValue("SP05 nouvelle saisie synthétique");
    await expect(invalidPhone).toHaveAttribute("aria-invalid", "false");
    await mobile.screenshot({ path: path.join(artifact, "sp05-create-mobile.png"), fullPage: true });
    await mobile.getByRole("button", { name: "Créer le Lead", exact: true }).tap();
    await dialog.getByRole("button", { name: `Réutiliser ${name}`, exact: true }).tap();
    await expect(mobile.getByText(`Contact choisi : ${name}`, { exact: true })).toBeVisible();
    await expect(mobile.getByRole("button", { name: "Créer le Lead", exact: true })).toBeFocused();
    await mobile.getByRole("button", { name: "Créer le Lead", exact: true }).tap();
    await expect.poll(() => /^\/leads\/[a-f0-9-]{36}$/.test(new URL(mobile.url()).pathname)).toBe(true);

    await clearActorContext(page);
    await signIn(page, other);
    await createLead(page, "SP05 identité privée synthétique", "+33600000002");
    await mobile.goto("/leads/new");
    await expect(mobile.getByRole("button", { name: "Créer le Lead", exact: true })).toBeEnabled();
    await mobile.getByLabel("Nom du contact", { exact: true }).fill("SP05 tentative synthétique");
    await mobile.getByLabel("Indicatif Téléphone 1 *", { exact: true }).selectOption("FR");
    await mobile.getByLabel("Téléphone 1 *", { exact: true }).fill("0600000002");
    await mobile.getByLabel("Langues parlées *", { exact: true }).selectOption("french");
    await mobile.getByLabel("Budget *", { exact: true }).selectOption("500.000 DH - 1.000.000 DH");
    await mobile.getByRole("button", { name: "Créer le Lead", exact: true }).tap();
    await expect(mobile.getByText("Aucun accès ni doublon n’a été créé.", { exact: false })).toBeVisible();
    await mobile.screenshot({ path: path.join(artifact, "sp05-private-mobile.png"), fullPage: true });
    expect(await mobile.getByText("SP05 identité privée synthétique", { exact: true }).count()).toBe(0);
    expect(errors).toEqual([]);
  } finally { await touch.close(); await removeActor(other); await removeActor(agent); }
});
