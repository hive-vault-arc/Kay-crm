import { test, expect, signIn, createActor, removeActor } from "../helpers/auth";
import { fillDeal, saveDeal } from "../helpers/deals";
import { captureQualificationPair } from "../helpers/qualification-captures";

test("KAY manual deal: client profile, project qualification, atomic edit and rich table", async ({ page }) => {
  test.setTimeout(150_000);
  const actor = await createActor("agent");
  const errors: string[] = [];
  page.on("pageerror", () => errors.push("APPLICATION_PAGE_ERROR"));
  try {
    await signIn(page, actor); await page.goto("/deals/new");
    const form = page.getByRole("form", { name: "Nouvelle affaire", exact: true });
    await expect(form.getByLabel("Nom du contact", { exact: true })).toBeEnabled();
    await expect(form.getByLabel("Titre de l’affaire", { exact: true })).toHaveCount(0);
    await form.getByLabel("Nom du contact", { exact: true }).fill("Client manuel synthétique");
    await form.getByLabel("Indicatif Téléphone 1 *", { exact: true }).selectOption("FR");
    await form.getByLabel("Téléphone 1 *", { exact: true }).fill("0600000002");
    await form.getByLabel("Pays de résidence", { exact: true }).selectOption("FR");
    await form.getByLabel("Nationalité (pays)", { exact: true }).selectOption("MA");
    await form.getByRole("button", { name: "Créer l’affaire", exact: true }).click();
    await expect(form.getByText("Choisissez au moins une langue.", { exact: true })).toBeVisible();
    await expect(form.getByLabel("Langues parlées *", { exact: true })).toBeFocused();
    await form.getByLabel("Langues parlées *", { exact: true }).selectOption("french");
    await expect(form.getByText("Choisissez au moins une langue.", { exact: true })).toHaveCount(0);
    await fillDeal(page, "Projet manuel synthétique");
    await form.getByLabel("Source", { exact: true }).selectOption("instagram_ads");
    await form.getByLabel("Qualification", { exact: true }).selectOption("hot");
    await form.getByLabel("Financement (facultatif)", { exact: true }).selectOption("mortgage");
    await form.getByLabel("Nombre de pièces (facultatif)", { exact: true }).fill("3");
    for (const width of [320, 390, 768, 1024, 1440]) {
      await page.setViewportSize({ width, height: 900 });
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    }
    await captureQualificationPair(page, "deal-create");
    const id = await saveDeal(page);
    const created = await (await page.request.get(`/api/v1/deals/${id}`)).json();
    expect(created.title).toBe("Client manuel synthétique · Projet manuel synthétique");
    expect(created.client_snapshot.calling_code).toBe("+33");
    expect(created.contact.primary_phone).toBe("+33600000002");
    expect(created.active_reservation).toBeNull(); expect(created.enquiry_id).toBeNull();
    await expect(page.getByRole("heading", { name: created.title, exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Modifier l’affaire et la prochaine action", exact: true }).click();
    const edit = page.getByRole("form", { name: "Modifier l’affaire", exact: true });
    await expect(page.getByRole("heading", { name: "Modifier l’affaire", exact: true })).toBeVisible();
    await expect(page.getByRole("heading", { name: "Pipeline", exact: true })).toHaveCount(0);
    await edit.getByLabel("Nom du contact", { exact: true }).fill("Client manuel actualisé");
    await edit.getByLabel("Pays de résidence", { exact: true }).selectOption("ES");
    await edit.getByLabel("Nationalité (pays)", { exact: true }).selectOption("FR");
    await edit.getByLabel("Budget *", { exact: true }).selectOption("1.000.000 DH - 2.000.000 DH");
    await edit.getByLabel("Notes", { exact: true }).fill("Qualification actualisée synthétique");
    await edit.getByRole("button", { name: "Ajouter un projet (maximum 3)", exact: true }).click();
    const alternative = edit.getByRole("region", { name: "Projet 2", exact: true });
    await alternative.getByLabel("Type de projet", { exact: true }).selectOption("external");
    await alternative.getByLabel("Nom du projet externe *", { exact: true }).fill("Alternative synthétique");
    await captureQualificationPair(page, "deal-edit");
    await edit.getByRole("button", { name: "Ajouter un projet (maximum 3)", exact: true }).click();
    const third = edit.getByRole("region", { name: "Projet 3", exact: true });
    await third.getByLabel("Type de projet", { exact: true }).selectOption("external");
    await third.getByLabel("Nom du projet externe *", { exact: true }).fill("Troisième intérêt synthétique");
    await expect(edit.getByRole("button", { name: "Ajouter un projet (maximum 3)", exact: true })).toHaveCount(0);
    await captureQualificationPair(page, "deal-edit-three-projects");
    await third.getByRole("button", { name: "Retirer le projet 3", exact: true }).click();
    await edit.getByRole("button", { name: "Enregistrer l’affaire", exact: true }).click();
    await expect(page.getByText("Affaire enregistrée.", { exact: true })).toBeVisible();
    const updated = await (await page.request.get(`/api/v1/deals/${id}`)).json();
    expect(updated.version).toBe(2); expect(updated.contact.version).toBe(2);
    expect(updated.contact.id).toBe(created.contact.id);
    expect(updated.projects.map((project: { name: string }) => project.name)).toEqual(["Projet manuel synthétique", "Alternative synthétique"]);
    expect(updated.client_snapshot.name).toBe("Client manuel actualisé");
    expect(updated.client_snapshot.country).toBe("ES");
    const history = await (await page.request.get(`/api/v1/deals/${id}/history`)).json();
    expect(history.items[1].qualification.client_snapshot.name).toBe("Client manuel synthétique");
    const events = page.getByRole("region", { name: "Historique de l’affaire", exact: true }).getByRole("listitem");
    await expect(events).toHaveCount(2);
    await events.first().getByText("Qualification enregistrée avec cette version", { exact: true }).click();
    await expect(events.first().getByText("Client manuel actualisé", { exact: true })).toBeVisible();
    await expect(events.first().getByText("Espagne", { exact: true })).toBeVisible();
    await expect(events.first().getByText("France", { exact: true })).toBeVisible();
    await expect(events.first().getByText("+33", { exact: true })).toBeVisible();
    await events.last().getByText("Qualification enregistrée avec cette version", { exact: true }).click();
    await expect(events.last().getByText("Client manuel synthétique", { exact: true })).toBeVisible();
    await expect(events.last().getByText("France", { exact: true })).toBeVisible();
    await expect(events.last().getByText("Maroc", { exact: true })).toBeVisible();
    await captureQualificationPair(page, "deal-detail");
    await page.goto("/deals");
    await expect(page.getByRole("columnheader", { name: "Budget", exact: true })).toBeVisible();
    await expect(page.getByRole("link", { name: "Client manuel actualisé", exact: true })).toBeVisible();
    await page.getByLabel("Source", { exact: true }).selectOption("facebook");
    await expect(page.getByText("0 affaire", { exact: true }).and(page.getByRole("status"))).toBeVisible();
    await page.locator('[data-filter-panel="desktop"]').getByRole("button", { name: "Effacer", exact: true }).click();
    await expect(page.getByText("1 affaire", { exact: true }).and(page.getByRole("status"))).toBeVisible();
    await page.getByRole("button", { name: "Colonnes", exact: true }).click();
    await page.getByRole("checkbox", { name: "Langues", exact: true }).check();
    await page.keyboard.press("Escape");
    await page.reload();
    await expect(page.getByRole("columnheader", { name: "Langues", exact: true })).toBeVisible();
    await captureQualificationPair(page, "deal-list");
    expect(errors).toEqual([]);
  } finally { await removeActor(actor); }
});
